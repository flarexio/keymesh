// Regenerates src/app/core/brand-icons.data.ts from the pinned simple-icons
// devDependency, keeping what the app draws (title, colour, path) plus each
// icon's provenance (source, brand guidelines) for the reviewed brands listed
// in src/app/core/brand-icons.ts. Offline.
//   node scripts/make-brand-icons.mjs
//
// Licensing: the simple-icons package is CC0-1.0, but upstream's DISCLAIMER
// says individual icons may carry their own licence and that missing licence
// data does not imply one. This script therefore REFUSES any icon whose
// metadata names a licence (e.g. CC-BY-SA-4.0) instead of silently shipping
// it, and records source and guidelines for every shipped icon. Brand marks
// remain trademarks of their owners.
import * as si from 'simple-icons';
import { readFile, writeFile } from 'node:fs/promises';

const here = (p) => new URL(p, import.meta.url);
const table = await readFile(here('../src/app/core/brand-icons.ts'), 'utf8');
const names = [...new Set([...table.matchAll(/\bb\((si[A-Za-z0-9]+),/g)].map((m) => m[1]))].sort();
const pkg = JSON.parse(await readFile(here('../node_modules/simple-icons/package.json'), 'utf8'));
const meta = JSON.parse(await readFile(here('../node_modules/simple-icons/data/simple-icons.json'), 'utf8'));
const metaList = Array.isArray(meta) ? meta : meta.icons;
const refused = [];
const rows = names.map((n) => {
  const icon = si[n];
  if (!icon) throw new Error(`simple-icons has no ${n}`);
  if (!/^[0-9A-F]{6}$/i.test(icon.hex) || !/^[MmLlHhVvCcSsQqTtAaZz0-9.,\s-]+$/.test(icon.path)) throw new Error(`unexpected data for ${n}`);
  const m = metaList.find((x) => x.title === icon.title && (x.slug ?? icon.slug) === icon.slug) ?? metaList.find((x) => x.title === icon.title);
  if (!m) throw new Error(`no metadata for ${n}`);
  if (m.license) refused.push(`${icon.title} (${m.license.type ?? JSON.stringify(m.license)})`);
  return [
    `/** ${icon.title}. Source: ${m.source}${m.guidelines ? `. Brand guidelines: ${m.guidelines}` : ''}. */`,
    `export const ${n}: SimpleIcon = { title: ${JSON.stringify(icon.title)}, hex: '${icon.hex}', path: '${icon.path}' };`,
  ].join('\n');
});
if (refused.length) {
  console.error(`refusing icons with their own licence (remove them from brand-icons.ts): ${refused.join(', ')}`);
  process.exit(1);
}
const out = `/* eslint-disable */
// GENERATED by scripts/make-brand-icons.mjs from simple-icons@${pkg.version}.
// Package licence: ${pkg.license}. No icon below has its own licence in the
// package metadata (the script refuses those); upstream notes that missing
// licence data does not by itself imply one. Brand names and logos remain
// trademarks of their owners and are shown only to identify a login's site:
// they are not a security or origin indicator. Do not edit by hand: edit
// the table in brand-icons.ts and rerun the script.

export interface SimpleIcon {
  title: string;
  hex: string;
  path: string;
}

${rows.join('\n\n')}
`;
await writeFile(here('../src/app/core/brand-icons.data.ts'), out);
console.log(`${names.length} brand icons from simple-icons@${pkg.version}; none with a per-icon licence`);
