// Regenerates src/app/core/brand-icons.data.ts from the pinned simple-icons
// devDependency, keeping only what the app draws (title, colour, path) for
// the reviewed brands listed in src/app/core/brand-icons.ts. Offline.
//   node scripts/make-brand-icons.mjs
import * as si from 'simple-icons';
import { readFile, writeFile } from 'node:fs/promises';

const here = (p) => new URL(p, import.meta.url);
const table = await readFile(here('../src/app/core/brand-icons.ts'), 'utf8');
const names = [...new Set([...table.matchAll(/\bb\((si[A-Za-z0-9]+),/g)].map((m) => m[1]))].sort();
const version = JSON.parse(await readFile(here('../node_modules/simple-icons/package.json'), 'utf8')).version;
const rows = names.map((n) => {
  const icon = si[n];
  if (!icon) throw new Error(`simple-icons has no ${n}`);
  if (!/^[0-9A-F]{6}$/i.test(icon.hex) || !/^[MmLlHhVvCcSsQqTtAaZz0-9.,\s-]+$/.test(icon.path)) throw new Error(`unexpected data for ${n}`);
  return `export const ${n}: SimpleIcon = { title: ${JSON.stringify(icon.title)}, hex: '${icon.hex}', path: '${icon.path}' };`;
});
const out = `/* eslint-disable */
// GENERATED by scripts/make-brand-icons.mjs from simple-icons@${version}
// (CC0-1.0; brand names and logos remain trademarks of their owners).
// Do not edit by hand: edit the table in brand-icons.ts and rerun the script.

export interface SimpleIcon {
  title: string;
  hex: string;
  path: string;
}

${rows.join('\n')}
`;
await writeFile(here('../src/app/core/brand-icons.data.ts'), out);
console.log(`${names.length} brand icons from simple-icons@${version}`);
