import type { SimpleIcon } from './brand-icons.data';

export interface Brand {
  id: string;
  title: string;
  /** Brand colour, `#rrggbb`. */
  hex: string;
  /** 24×24 SVG path. */
  path: string;
  domains: readonly string[];
}

const b = (icon: SimpleIcon, domains: string[]): Brand => ({
  id: icon.title.toLowerCase().replace(/[^a-z0-9]+/g, '-'),
  title: icon.title,
  hex: '#' + icon.hex,
  path: icon.path,
  domains,
});

